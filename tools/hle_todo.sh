#!/usr/bin/env bash
# Run the host for N seconds (default 45) and turn its log into docs/HLE_TODO.md:
# every import / ObjC selector the guest called that the host does not implement yet (the porting backlog).
#   usage: tools/hle_todo.sh <path to .app> [seconds]
set -uo pipefail
cd "$(dirname "$0")/.."
APP=${1:?path to .app}; SECS=${2:-45}
LOG=$(mktemp); SDL_VIDEODRIVER=${SDL_VIDEODRIVER:-offscreen} RA_NOVSYNC=1 timeout "$SECS" host/build/ra_host --app "$APP" >"$LOG" 2>&1
{
  echo "# HLE backlog (generated by tools/hle_todo.sh, ${SECS}s run)"; echo
  echo "## Unimplemented imports ($(grep -o 'UNIMPLEMENTED import [A-Za-z0-9_]*' "$LOG" | sort -u | wc -l))"; echo
  grep -o 'UNIMPLEMENTED import [A-Za-z0-9_]*' "$LOG" | sort -u | awk '{print "- `"$3"`"}'; echo
  echo "## Unhandled ObjC selectors ($(grep -o 'unhandled -\[[A-Za-z0-9_]* [^]]*\]' "$LOG" | sort -u | wc -l)) - the host answers nil"; echo
  grep -o 'unhandled -\[[A-Za-z0-9_]* [^]]*\]' "$LOG" | sort -u | sed 's/unhandled /- `/; s/$/`/'; echo
  echo "## Faults"; echo; grep -E 'emu error|memory fault|invalid receiver' "$LOG" | sort | uniq -c | head -10 | sed 's/^/    /'
} > docs/HLE_TODO.md
echo "wrote docs/HLE_TODO.md"; rm -f "$LOG"
