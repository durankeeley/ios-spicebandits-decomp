#!/usr/bin/env python3
"""Generate docs/ from work/<tag>/functions.json.
usage: gen_docs.py <tag> <binary>
Outputs: docs/FUNCTIONS_<tag>.md, docs/functions_<tag>.csv, docs/IMPORTS.md
Human-assigned names live in tools/names_<tag>.json ({"0x1234": "Name"}) and override the auto labels.
"""
import sys, json, os, collections, subprocess, re
tag, binpath = sys.argv[1], sys.argv[2]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fn = {int(k): v for k, v in json.load(open(f"{root}/work/{tag}/functions.json")).items()}
names_p = f"{root}/tools/names_{tag}.json"
names = {int(k, 16): v for k, v in (json.load(open(names_p)) if os.path.exists(names_p) else {}).items()}

CATS = [("gl", ("gl",)), ("audio", ("Audio", "AL")), ("net", ("socket", "connect", "send", "recv", "bind", "listen", "accept", "select",
        "gethostbyname", "getifaddrs", "inet_", "SCNetwork", "NSURL")), ("file", ("fopen", "fread", "fwrite", "fseek", "ftell", "fclose",
        "open", "read", "write", "lseek", "fstat", "mkdir", "remove", "CFBundle", "NSFileManager")), ("db", ("sqlite3",)),
        ("objc/ui", ("objc_", "OBJC_", "UI", "NS", "CF", "CA", "EAGL")), ("math/str", ("memcpy", "memset", "memmove", "strlen", "strcmp",
        "strcpy", "strncmp", "sscanf", "sprintf", "snprintf", "atoi", "strchr", "vsprintf"))]
def cat_of(sym):
    for c, pre in CATS:
        if sym.startswith(pre): return c
    return "other"

callers = collections.defaultdict(set)
for a, f in fn.items():
    for c in f["callees"]: callers[c].add(a)

cls_p = f"{root}/work/{tag}/classes.json"
vslot = {}   # function addr -> "Class::vfN"
classes = json.load(open(cls_p)) if os.path.exists(cls_p) else {}
for cn, r in classes.items():
    for k, m in enumerate(r["methods"]):
        if (m & ~1) in fn: vslot.setdefault(m & ~1, f"{r['name']}::vf{k}")

exp_p = f"{root}/work/{tag}/exports.json"
exports = {int(k): v for k, v in json.load(open(exp_p)).items()} if os.path.exists(exp_p) else {}

om_p = f"{root}/work/{tag}/objc_methods.json"
objc = {int(k): v for k, v in json.load(open(om_p)).items()} if os.path.exists(om_p) else {}

def label(a, f):
    if a in names: return names[a]
    if a in objc: return objc[a].replace("|", "/")
    if a in exports: return exports[a].replace("|", "/")
    if a in vslot: return vslot[a]
    cats = collections.Counter(cat_of(s) for s in f["imports"])
    cats.pop("math/str", None); cats.pop("other", None)
    if f["strings"]:
        s = re.sub(r"[^A-Za-z0-9]+", "_", f["strings"][0])[:24].strip("_")
        if s: return f"fn_{a:x}__{s}"
    if cats: return f"{cats.most_common(1)[0][0].replace('/','_')}_{a:x}"
    return f"sub_{a:x}"

# ---- CSV
os.makedirs(f"{root}/docs", exist_ok=True)
with open(f"{root}/docs/functions_{tag}.csv", "w") as o:
    o.write("addr,size,label,callers,callees,vfp,neon,imports\n")
    for a, f in sorted(fn.items()):
        o.write(f"0x{a:x},{f['size']},{label(a,f)},{len(callers[a])},{len(f['callees'])},{f['vfp']},{f['neon']},{'|'.join(f['imports'])}\n")

# ---- per-category rollup
bycat = collections.defaultdict(list)
for a, f in fn.items():
    cs = {cat_of(s) for s in f["imports"]} - {"other", "math/str"}
    for c in cs or {"pure (no platform calls)"}: bycat[c].append(a)

L = [f"# Function map — {tag}\n",
     "Generated by `tools/gen_docs.py` from `tools/find_functions.py` output. **Labels are heuristic** "
     "(string/import based); override them in `tools/names_%s.json` and re-run." % tag,
     f"\n- Functions discovered: **{len(fn)}**, total {sum(f['size'] for f in fn.values())//1024} KB",
     f"- Functions using VFP/NEON: {sum(1 for f in fn.values() if f['vfp'])}",
     "\n## Platform-touching functions by subsystem\n", "| subsystem | functions | bytes |", "|---|---|---|"]
for c, v in sorted(bycat.items(), key=lambda x: -len(x[1])):
    L.append(f"| {c} | {len(v)} | {sum(fn[a]['size'] for a in v)} |")

L += ["\n## Roots (no callers inside __text — entry points, vtable methods, callbacks)\n",
      f"{sum(1 for a in fn if not callers[a])} functions are never directly called; most are C++ virtual methods reached through vtables "
      "(see `docs/BINARY_NOTES.md`, 'Lifting hazards').\n"]

for c in sorted(bycat, key=lambda c: -len(bycat[c])):
    if c.startswith("pure"): continue
    L.append(f"\n## {c}\n")
    L.append("| addr | size | label | calls (platform) | strings | callers |\n|---|---|---|---|---|---|")
    for a in sorted(bycat[c])[:400]:
        f = fn[a]
        imp = ", ".join(f"{k}×{v}" if v > 1 else k for k, v in sorted(f["imports"].items()))[:110]
        st = "; ".join(s.replace("|", "/")[:28] for s in f["strings"][:3])
        L.append(f"| `0x{a:x}` | {f['size']} | {label(a,f)} | {imp} | {st} | {len(callers[a])} |")

L.append(f"\n## Exported symbols\n{len(exports)} functions carry real names from the Mach-O exports trie "
         f"({sum(1 for a in exports if a in fn)} of them match discovered functions). Full list: `docs/EXPORTS_{tag}.md`.\n")
open(f"{root}/docs/EXPORTS_{tag}.md", "w").write(f"# Exported symbols {tag}\n\n| addr | name |\n|---|---|\n" + "\n".join(f"| `0x{a:x}` | `{n.replace('|','/')}` |" for a, n in sorted(exports.items())) + "\n")
L.append(f"\n## Objective-C methods\n{len(objc)} methods named from ObjC metadata ({sum(1 for a in objc if a in fn)} match discovered functions). Full list: `docs/OBJC_{tag}.md`.\n")
open(f"{root}/docs/OBJC_{tag}.md", "w").write(f"# Objective-C methods {tag}\n\n| imp | method |\n|---|---|\n" + "\n".join(f"| `0x{a:x}` | `{n.replace('|','/')}` |" for a, n in sorted(objc.items())) + "\n")
L.append("\n## C++ classes recovered from RTTI\n")
L.append("`vfN` = virtual slot N (slot 0/1 are usually the destructors). Full table: `docs/CLASSES_%s.md`.\n" % tag)
L.append(f"{len(classes)} classes; {len(vslot)} functions named via vtables.\n")
L.append("\n## Largest functions (likely game-logic / parsers / AI)\n")
L.append("| addr | size | label | callees | strings |\n|---|---|---|---|---|")
for a, f in sorted(fn.items(), key=lambda x: -x[1]["size"])[:60]:
    L.append(f"| `0x{a:x}` | {f['size']} | {label(a,f)} | {len(f['callees'])} | {'; '.join(s[:30] for s in f['strings'][:3])} |")

L.append("\n## Functions referencing data/script file names\n")
for a, f in sorted(fn.items()):
    hits = [s for s in f["strings"] if re.search(r"\.(bin|pvr|vfs|xGDF|xWorld|xEntity|png|fnt|plist|txt)\b|stats/|levels/|scripts/", s)]
    if hits: L.append(f"- `0x{a:x}` {label(a,f)} ({f['size']}B): " + ", ".join(hits[:4]))
open(f"{root}/docs/FUNCTIONS_{tag}.md", "w").write("\n".join(L) + "\n")
print("wrote docs/FUNCTIONS_%s.md, functions_%s.csv" % (tag, tag))

# ---- CLASSES_<tag>.md
if classes:
    C = [f"# C++ classes — Spice Bandits (Tower) {tag}\n", "From Itanium RTTI (`tools/rtti.py`). Slot index = vtable position; "
         "`thumb` marks Thumb-2 entry points. Methods that are `-` are pure-virtual / imports.\n"]
    kids = collections.defaultdict(list)
    for cn, r in classes.items():
        for bse in r["bases"]: kids[bse].append(r["name"])
    roots = [r["name"] for r in classes.values() if not r["bases"]]
    def tree(n, d=0):
        C.append("  " * d + f"- `{n}`")
        for k in sorted(kids.get(n, [])): tree(k, d + 1)
    C.append("## Hierarchy\n")
    for n in sorted(roots): tree(n)
    C.append("\n## Vtables\n")
    for cn, r in sorted(classes.items(), key=lambda x: x[1]["name"]):
        if not r["vtable"]: continue
        C.append(f"\n### {r['name']}" + (f" : {', '.join(r['bases'])}" if r["bases"] else "") + f"\n`typeinfo 0x{r['typeinfo']:x}  vtable 0x{r['vtable']:x}  slots {len(r['methods'])}`\n")
        C.append("| slot | addr | mode | size | notes |\n|---|---|---|---|---|")
        for k, m in enumerate(r["methods"]):
            a = m & ~1
            f = fn.get(a)
            note = ""
            if f:
                note = ", ".join(sorted(f["imports"])[:4]) + (" · " + "; ".join(s[:24] for s in f["strings"][:2]) if f["strings"] else "")
            C.append(f"| {k} | `0x{a:x}` | {'thumb' if m & 1 else 'arm'} | {f['size'] if f else '-'} | {note} |")
    open(f"{root}/docs/CLASSES_{tag}.md", "w").write("\n".join(C) + "\n")
    print("wrote docs/CLASSES_%s.md" % tag)
